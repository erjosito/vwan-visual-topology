import { expect, test } from '@playwright/test'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { parseAzNetJson } from '../src/azure-net/admission'
import { simulateAzNet, traceAzNetFlow } from '../src/azure-net/engine'

for (const mode of ['hub-spoke', 'full']) {
  test(`${mode} authors selected subnet scope, keeps stable IDs and original flags, and restores scope through history and reload`, async ({ page }) => {
    const topology = parseAzNetJson(readFileSync(resolve('public', 'docs', 'samples', 'azure-net', 'subnet-peering.json'), 'utf8'))
    delete topology.vnetPeerings[0].scope
    await page.addInitScript((value) => {
      if (!localStorage.getItem('aznet-visual-topology:v1')) localStorage.setItem('aznet-visual-topology:v1', JSON.stringify({ sampleId: '', topology: value }))
    }, topology)
    await page.goto(`/?mode=${mode}`)
    await page.getByTestId('aznet-peering-peer-a-b').focus()
    await page.keyboard.press('Shift+F10')
    await page.getByRole('menuitem', { name: 'Configure Peering State & Flags', exact: true }).click()
    const editor = page.getByTestId('peering-scope-editor')
    await expect(editor.getByLabel('Peering scope', { exact: true })).toHaveValue('whole-vnet')
    await editor.getByLabel('Peering scope', { exact: true }).selectOption('subnets')
    await expect(editor.getByRole('button', { name: 'Apply peering scope', exact: true })).toBeDisabled()
    await expect(editor).toContainText('Azure requires deleting and recreating')
    await editor.getByRole('checkbox', { name: 'VNet A: Participating A (a1)', exact: true }).check()
    await editor.getByRole('checkbox', { name: 'VNet B: Participating B (b1)', exact: true }).check()
    await editor.getByRole('button', { name: 'Apply peering scope', exact: true }).click()
    const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem('aznet-visual-topology:v1')!).topology)
    await expect.poll(async () => (await saved()).vnetPeerings[0].scope).toEqual({ type: 'subnets', subnetAIds: ['a1'], subnetBIds: ['b1'] })
    const selected = await saved()
    expect(selected.vnetPeerings[0].id).toBe('peer-a-b')
    expect(selected.vnetPeerings[0].aToB).toEqual(topology.vnetPeerings[0].aToB)
    expect(selected.vnets).toEqual(topology.vnets)
    const simulation = simulateAzNet(selected)
    expect(simulation.subnetTables.a2.routes.some((route) => route.prefix === '10.81.1.0/24')).toBe(true)
    expect(traceAzNetFlow(selected, simulation, { kind: 'subnet', vnetId: 'vnet-a', subnetId: 'a2' }, '10.81.1.4').status).toBe('dropped-peering-access')
    await page.getByTestId('aznet-subnet-a2').focus()
    await page.keyboard.press('Shift+F10')
    await page.getByRole('menuitem', { name: 'Inspect Subnet Effective Routes', exact: true }).click()
    await expect(page.getByTestId('aznet-effective-route-table')).toContainText('10.81.1.0/24')
    await expect(page.getByTestId('aznet-effective-route-table')).not.toContainText('10.81.0.0/16')
    await page.getByTestId('aznet-subnet-a2').focus()
    await page.keyboard.press('Shift+F10')
    await page.getByRole('menuitem', { name: 'Open path explorer', exact: true }).click()
    await page.getByTestId('aznet-trace-source-select').selectOption('subnet:vnet-a:a2')
    await page.getByTestId('aznet-trace-dest-select').selectOption('subnet:vnet-b:b1')
    await expect(page.getByTestId('aznet-forward-hops')).toContainText('both source and destination subnets participate')
    await page.getByRole('button', { name: '↶ Undo', exact: true }).click()
    await expect.poll(async () => (await saved()).vnetPeerings[0].scope).toBeUndefined()
    await page.getByRole('button', { name: '↷ Redo', exact: true }).click()
    await expect.poll(async () => (await saved()).vnetPeerings[0].scope).toEqual(selected.vnetPeerings[0].scope)
    await page.reload()
    expect((await saved()).vnetPeerings[0].scope).toEqual(selected.vnetPeerings[0].scope)
    await page.getByTestId('aznet-peering-peer-a-b').focus()
    await page.keyboard.press('Shift+F10')
    await page.getByRole('menuitem', { name: 'Configure Peering State & Flags', exact: true }).click()
    await expect(editor.getByRole('checkbox', { name: 'VNet A: Participating A (a1)', exact: true })).toBeChecked()
    await editor.getByRole('checkbox', { name: 'VNet A: Unselected A (a2)', exact: true }).check()
    await editor.getByRole('button', { name: 'Apply peering scope', exact: true }).click()
    await expect.poll(async () => (await saved()).vnetPeerings[0].scope.subnetAIds).toEqual(['a1', 'a2'])
  })
}

test('localizes subnet authoring in a narrow dark workspace without accessibility violations', async ({ page }) => {
  const { default: AxeBuilder } = await import('@axe-core/playwright')
  await page.setViewportSize({ width: 700, height: 900 })
  await page.goto('/?mode=full')
  await page.getByRole('combobox', { name: 'Sample Topology:', exact: true }).selectOption('subnet-peering')
  await page.getByTestId('aznet-peering-peer-a-b').focus()
  await page.keyboard.press('Shift+F10')
  await page.getByRole('menuitem', { name: 'Configure Peering State & Flags', exact: true }).click()
  await page.getByRole('combobox', { name: 'Theme', exact: true }).selectOption('dark')
  await page.getByRole('combobox', { name: 'Language / 言語', exact: true }).selectOption('ja')
  const editor = page.getByTestId('peering-scope-editor')
  await expect(editor.getByLabel('ピアリングの範囲', { exact: true })).toHaveValue('subnets')
  await expect(editor.getByRole('button', { name: 'ピアリングの範囲を適用', exact: true })).toBeVisible()
  expect((await new AxeBuilder({ page }).include('[data-testid="peering-scope-editor"]').analyze()).violations).toEqual([])
})

test('diagram editing renames objects without losing IDs, routes or policies', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Private traffic routing intent', { exact: true }).check()
  await page.getByRole('button', { name: 'London primary', exact: true }).click()
  await page.getByRole('button', { name: 'Add inbound rule', exact: true }).click()
  const before = await readTopology(page)
  const actions = page.getByRole('region', { name: 'Selected topology object' })
  const changes = [
    { selector: 'Select hub Europe hub', kind: 'hub', name: 'EU core' },
    { selector: 'Select spoke Europe applications', kind: 'spoke', name: 'EU workloads' },
    { selector: 'Select site London datacenter', kind: 'site', name: 'London campus' },
    { selector: 'Edit connection London primary', kind: 'connection', name: 'London circuit' },
  ]
  for (const change of changes) {
    await page.getByLabel(change.selector, { exact: true }).focus()
    await page.keyboard.press('Enter')
    await actions.getByRole('button', { name: `Edit ${change.kind}`, exact: true }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('Name', { exact: true }).fill(change.name)
    if (change.kind === 'site') {
      await expect(dialog.getByLabel('Site ASN', { exact: true })).toHaveValue('65010')
      await dialog.getByLabel('Site ASN', { exact: true }).fill('65110')
    }
    if (change.kind === 'spoke') {
      await dialog.getByLabel('Prefixes', { exact: true }).fill('10.1.0.7/16')
      await dialog.getByRole('button', { name: 'Save changes', exact: true }).click()
      await expect(dialog.getByRole('alert')).toContainText('Invalid spoke IPv4')
      expect((await readTopology(page)).spokes).toEqual(before.spokes)
      await dialog.getByLabel('Prefixes', { exact: true }).fill('10.1.0.0/16')
    }
    await dialog.getByRole('button', { name: 'Save changes', exact: true }).click()
    await expect(dialog).toHaveCount(0)
  }
  const after = await readTopology(page)
  expect(after.hubs).toEqual(before.hubs.map((h) => h.id === 'eu' ? { ...h, name: 'EU core' } : h))
  expect(after.spokes).toEqual(before.spokes.map((s) => s.id === 'eu-apps' ? { ...s, name: 'EU workloads' } : s))
  expect(after.sites).toEqual(before.sites.map((s) => s.id === 'dc' ? { ...s, name: 'London campus', asn: 65110 } : s))
  expect(after.connections).toEqual(before.connections.map((c) => c.id === 'er-eu' ? { ...c, name: 'London circuit' } : c))
  await page.reload()
  await expect(page.getByLabel('Select hub EU core', { exact: true })).toBeVisible()
  await expect(page.getByLabel('Edit connection London circuit', { exact: true })).toBeAttached()
  await expect(page.getByLabel('Select site London campus', { exact: true })).toContainText('ASN 65110')
})


import { expect, test } from '@playwright/test'

test('clicking hubs highlights routes, HRP changes winners, and trace crosses hubs', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await page.getByLabel('Select hub Europe hub', { exact: true }).click()
  await page.getByLabel('Highlight prefix', { exact: true }).selectOption('10.20.0.0/16')
  await expect(page.getByTestId('link-er-eu')).toHaveAttribute('data-preferred', 'true')
  await expect(page.getByTestId('link-vpn-eu')).toHaveAttribute('data-preferred', 'false')
  await page.getByLabel('Hub routing preference', { exact: true }).selectOption('VPN')
  await expect(page.getByTestId('link-vpn-eu')).toHaveAttribute('data-preferred', 'true')
  await page.getByLabel('Destination IPv4').fill('10.30.0.25')
  await page.getByRole('button', { name: 'Trace flow', exact: true }).click()
  await expect(page.locator('.flow-result')).toContainText('Europe hub → Americas hub → New York VPN → New York office')
  await expect(page.getByTestId('interhub-eu-us')).toHaveClass(/preferred-link/)
  await page.getByRole('button', { name: 'Hide effective routes' }).click()
  await expect(page.locator('.effective-routes table')).toHaveCount(0)
  await page.getByRole('button', { name: 'Show effective routes' }).click()
  await expect(page.locator('.effective-routes table')).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Hub routing preference', { exact: true })).toHaveValue('VPN')
  expect(errors).toEqual([])
})

test('adds a spoke, shows its route, and preserves it across JSON export/import', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('tab', { name: 'Spokes', exact: true }).click()
  await page.getByLabel('Spoke name', { exact: true }).fill('Analytics VNet')
  await page.getByLabel('Spoke prefixes', { exact: true }).fill('10.70.0.0/16')
  await page.getByRole('button', { name: 'Add spoke', exact: true }).click()
  await expect(page.locator('.diagram')).toContainText('Analytics VNet')
  await expect(page.locator('.effective-routes table')).toContainText('10.70.0.0/16')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export JSON' }).click()
  const download = await downloadPromise
  const path = await download.path()
  await page.getByRole('button', { name: 'Load example (replaces workspace)', exact: true }).click()
  await expect(page.locator('.diagram')).not.toContainText('Analytics VNet')
  await page.getByLabel('Import topology file').setInputFiles(path!)
  await expect(page.locator('.diagram')).toContainText('Analytics VNet')
})

test('routing intent separates hub and firewall routes and inspects a flow', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Private traffic routing intent', { exact: true }).check()
  await expect(page.locator('.effective-routes table')).toContainText('10.0.0.0/8')
  await expect(page.locator('.effective-routes table')).not.toContainText('10.20.0.0/16')
  await page.getByLabel('Effective route view', { exact: true }).selectOption('firewall')
  await expect(page.locator('.effective-routes table')).toContainText('10.20.0.0/16')
  await page.getByLabel('Destination IPv4').fill('10.20.1.1')
  await page.getByRole('button', { name: 'Trace flow', exact: true }).click()
  await expect(page.locator('.flow-result')).toContainText('Azure Firewall')
  await page.getByLabel('Edit connection London primary', { exact: true }).focus()
  await page.keyboard.press('Enter')
  await page.getByRole('button', { name: 'Add inbound rule', exact: true }).click()
  await expect(page.getByLabel('inbound prepend ASNs 1')).toHaveValue('64496')
  await page.screenshot({ path: 'test-results/topology.png', fullPage: true })
})

test('imports are validated without replacing the workspace and mobile UI works', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByLabel('Import topology file').setInputFiles({
    name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{"version":99}'),
  })
  await expect(page.getByRole('alert')).toContainText('Import rejected')
  await expect(page.getByLabel('Topology name')).toHaveValue('Global branch network')
  await expect(page.getByRole('button', { name: 'Trace flow', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})

